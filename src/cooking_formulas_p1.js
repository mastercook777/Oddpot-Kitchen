export const CB_MAIN_IDS=Object.freeze([...new Set(rows.map(row=>row[1]))]);
const local=new Set(['cloud_rice','sky_moss','storm_egg','sour_bell','gale_core']);
const pantry=new Set([...local,'chicken','onion','chili','garlic','mushroom','beef','potato']);
export function cbFormulaIngredientsAllowed(world,ids,vessel){
 if(!Array.isArray(ids)||ids.length<2||ids.length>3||new Set(ids).size!==ids.length||!ids.every(id=>Object.hasOwn(ING,id)))return false;
 return world==='cloud'?['WOK','POT','STEAM'].includes(vessel)&&ids.some(id=>local.has(id))&&ids.every(id=>pantry.has(id)):['WOK','POT','GRILL'].includes(vessel)&&ids.every(id=>!local.has(id));
}
const material=ids=>ids.reduce((n,id)=>n+ING[id].cost,0);
export const CB_FORMULAS=Object.freeze(Object.fromEntries(rows.map(([signature,recipeId,kind])=>{
 const [vessel,raw]=signature.split(':'),ingredientIds=raw.split(','),r=RECIPES[recipeId],world=ingredientIds.some(id=>local.has(id))?'cloud':'hearth';
 const materialCost=material(ingredientIds),baseCost=material(r.ids);
 const originalTags=new Set(r.ids.flatMap(id=>ING[id].tags)),actualTags=new Set(ingredientIds.flatMap(id=>ING[id].tags));
 const recipeTags=kind==='standard'?[...r.tags]:[...new Set([...r.tags.filter(t=>!originalTags.has(t)||actualTags.has(t)),...actualTags])];
 return [signature,Object.freeze({signature,formulaId:recipeId+'@'+raw,recipeId,kind,vessel,world,ingredientIds:Object.freeze(ingredientIds),materialCost,basePrice:kind==='standard'?r.price:Math.max(1,Math.round(r.price+materialCost-baseCost)),baseTime:kind==='standard'?r.time:r.time+Math.max(0,ingredientIds.length-r.ids.length)*1.5,recipeTags:Object.freeze(recipeTags)})];
})));
export function resolveCBFormula(ids,vessel,world){
 if(!cbFormulaIngredientsAllowed(world,ids,vessel))return null;
 const f=CB_FORMULAS[vessel+':'+[...ids].sort().join(',')];return f?.world===world?f:null;
}
export function cbIngredientInWorld(world,id){return Object.hasOwn(ING,id)&&(world==='cloud'?pantry.has(id):!local.has(id));}
